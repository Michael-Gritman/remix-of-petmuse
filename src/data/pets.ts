/**
 * Image layer — kept separate from UI so photography can be swapped for a
 * CDN / API later without touching a single component.
 */
const UNSPLASH = "https://images.unsplash.com/";

export function photo(id: string, width = 800): string {
  if (!id.startsWith("photo-")) return id;
  return `${UNSPLASH}${id}?auto=format&fit=crop&w=${width}&q=70`;
}

export function photoSrcSet(id: string): string | undefined {
  if (!id.startsWith("photo-")) return undefined;
  return [400, 600, 800, 1200]
    .map((w) => `${photo(id, w)} ${w}w`)
    .join(", ");
}

